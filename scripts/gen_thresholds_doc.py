"""Generate docs/thresholds.md from Thresholds.items() (BUILD_PLAN M10; CLAUDE.md §6 item 4).

Values are never hand-typed in the doc: this script prints them from the spec defaults
(`Thresholds()`), and, when configs/thresholds.yaml exists, the values in force with a
`differs` mark where they are not the default.

    uv run python scripts/gen_thresholds_doc.py            # rewrites docs/thresholds.md
    uv run python scripts/gen_thresholds_doc.py --check    # exit 1 when the doc is stale
"""
from __future__ import annotations

import sys
from pathlib import Path

from duplexbench.thresholds import DEFAULT_PATH, Thresholds

DOC = Path(__file__).resolve().parents[1] / "docs" / "thresholds.md"


def _fmt(v) -> str:
    if isinstance(v, (list, tuple)):
        return ", ".join(_fmt(x) for x in v)
    return str(v)


def render() -> str:
    default = Thresholds()
    in_force = Thresholds.load() if DEFAULT_PATH.exists() else default
    lines = [
        "# Thresholds",
        "",
        "Generated by `scripts/gen_thresholds_doc.py` from `Thresholds.items()`; do not edit by hand.",
        "Every number lives in `src/duplexbench/thresholds.py` (spec defaults) and",
        "`configs/thresholds.yaml` (values in force). Changing one is a human decision",
        "(CLAUDE.md §6 item 4) recorded in `docs/decisions.md`, and changes the thresholds hash,",
        "so results before and after never aggregate (spec §11).",
        "",
        f"- spec-default hash: `{default.hash()}`",
        f"- in-force hash: `{in_force.hash()}`"
        + ("" if DEFAULT_PATH.exists() else " (no configs/thresholds.yaml: defaults)"),
        "",
        "| name | spec default | in force | source | spec § |",
        "|---|---|---|---|---|",
    ]
    d_items, f_items = default.items(), in_force.items()
    for name, e in d_items.items():
        f = f_items[name]
        mark = "" if f["value"] == e["value"] else " (differs)"
        lines.append(f"| `{name}` | {_fmt(e['value'])} | {_fmt(f['value'])}{mark} | "
                     f"{e['source']} | {e['spec']} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        cur = DOC.read_text(encoding="utf-8") if DOC.exists() else ""
        if cur != text:
            print(f"{DOC} is stale; run scripts/gen_thresholds_doc.py")
            return 1
        return 0
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DOC} ({len(Thresholds.model_fields)} thresholds)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

"""Reference-ASR candidate table (BUILD_PLAN M4a-T02; spec §4.3) -> docs/refasr-candidates.md.

    from duplexbench.refasr.candidates_table import render, write, CANDIDATES
    md = render(measurements={"faster-whisper": {"wer": 0.041, "rtf": 0.31}})
    write(path, measurements)

Static facts (license, size, streaming, word timestamps, input rate) are
recorded as [Assumption] until someone confirms them on the model card; nothing
here was downloaded. Measured cells (WER on floor-mini, RTF on the laptop CPU,
partial-latency p90 in streaming mode) stay "[Assumption]/unmeasured" until
`duplexbench refasr-bench --yes` fills them. A human picks the model
(CLAUDE.md §6 item 3); this module never ranks or recommends.
"""
from __future__ import annotations

import importlib
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path

DOC_PATH = Path(__file__).resolve().parents[3] / "docs" / "refasr-candidates.md"
UNMEASURED = "[Assumption]/unmeasured; run `duplexbench refasr-bench --yes`"
COLUMNS = ("candidate", "license", "size", "streaming", "word timestamps", "8 kHz support",
           "WER floor-mini", "RTF", "partial p90")


@dataclass(frozen=True)
class Candidate:
    name: str                    # table key and wrapper `name`
    module: str                  # duplexbench.refasr.candidates.<module>
    cls: str                     # wrapper class
    model: str
    license: str
    size: str
    streaming: str
    word_timestamps: str
    rate_8k: str


_A = "[Assumption] "
CANDIDATES: tuple[Candidate, ...] = (
    Candidate("faster-whisper", "faster_whisper", "FasterWhisperASR", "large-v3-turbo",
              _A + "MIT (code and weights); verify", _A + "~809M params, ~1.6 GB fp16",
              "no (batch; wrapper buffers)", "yes", "no (16 kHz input; upsampled)"),
    Candidate("parakeet-tdt-0.6b-v3", "parakeet", "ParakeetASR", "nvidia/parakeet-tdt-0.6b-v3",
              _A + "CC-BY-4.0 weights; verify", _A + "~600M params, ~2.4 GB",
              "no (batch; wrapper buffers)", "yes", "no (16 kHz input; upsampled)"),
    Candidate("nemotron-streaming-0.6b", "parakeet", "NemotronStreamingASR",
              "nvidia/nemotron-speech-streaming-en-0.6b",
              _A + "NVIDIA open model license; id and license unverified", _A + "~600M params",
              "yes (native, cache-aware); wrapper buffers", "yes",
              "no (16 kHz input; upsampled)"),
    Candidate("kyutai-stt", "kyutai", "KyutaiASR", "kyutai/stt-2.6b-en-trfs",
              _A + "CC-BY-4.0 weights, MIT/Apache code; verify", _A + "1B or 2.6B params",
              "yes (native, moshi runtime); wrapper buffers",
              "native yes; transformers path no", "no (24 kHz input; upsampled)"),
    Candidate("moonshine", "moonshine", "MoonshineASR", "moonshine/base",
              _A + "MIT; verify", _A + "~61M params (base), ~27M (tiny)",
              "no (batch; wrapper buffers)", "no", "no (16 kHz input; upsampled)"),
)


def probe(c: Candidate) -> str | None:
    """None when the candidate's packages import here, else why not (no download)."""
    mod = importlib.import_module(f"duplexbench.refasr.candidates.{c.module}")
    return mod.probe()


def _fmt(v: object, kind: str) -> str:
    if v is None:
        return UNMEASURED
    if isinstance(v, str):
        return v
    if kind == "wer":
        return f"{float(v) * 100:.1f}%"
    if kind == "p90":
        return f"{float(v):.0f} ms"
    return f"{float(v):.2f}"


def rows(measurements: Mapping[str, Mapping[str, object]] | None = None) -> list[list[str]]:
    m = measurements or {}
    out = []
    for c in CANDIDATES:
        meas = m.get(c.name, {})
        out.append([f"{c.name} (`{c.model}`)", c.license, c.size, c.streaming,
                    c.word_timestamps, c.rate_8k, _fmt(meas.get("wer"), "wer"),
                    _fmt(meas.get("rtf"), "rtf"), _fmt(meas.get("partial_p90_ms"), "p90")])
    return out


def render(measurements: Mapping[str, Mapping[str, object]] | None = None,
           availability: Mapping[str, str | None] | None = None) -> str:
    avail = availability if availability is not None else {c.name: probe(c) for c in CANDIDATES}
    lines = [
        "# Reference-ASR candidates (BUILD_PLAN M4a-T02)",
        "",
        "Generated by `duplexbench.refasr.candidates_table`. Facts marked [Assumption] are",
        "from memory and must be confirmed on the model card before a pick; measured cells",
        "need model downloads, which need approval (`duplexbench refasr-bench --yes`).",
        "**A human picks the model (CLAUDE.md §6 item 3).** This table does not rank.",
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "|".join("---" for _ in COLUMNS) + "|",
    ]
    lines += ["| " + " | ".join(r) + " |" for r in rows(measurements)]
    lines += ["", "## Availability on this machine", ""]
    for c in CANDIDATES:
        why = avail.get(c.name)
        lines.append(f"- {c.name}: " + ("packages importable" if why is None
                                        else f"blocked: {why}"))
    lines += ["", "WER is on `tests/fixtures/floor-mini/` (20 TTS read-backs through C0 and C1,",
              "M2-T04); RTF on the laptop CPU; partial p90 only where the wrapper streams with",
              "partials (every wrapper here buffers until a model is picked).", ""]
    return "\n".join(lines)


def write(path: Path | str = DOC_PATH,
          measurements: Mapping[str, Mapping[str, object]] | None = None,
          availability: Mapping[str, str | None] | None = None) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render(measurements, availability), encoding="utf-8")
    return p
